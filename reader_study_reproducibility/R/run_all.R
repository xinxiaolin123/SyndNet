if(.Platform$OS.type=="windows") invisible(Sys.setlocale("LC_CTYPE","English_United States.utf8"))
args <- commandArgs(trailingOnly=FALSE)
script <- sub("^--file=","",args[grepl("^--file=",args)])
code_root <- Sys.getenv("SYNDNET_READER_STUDY_CODE_ROOT",if(length(script)) dirname(script[1]) else "reader_study_reproducibility/R")
code_root <- normalizePath(code_root,winslash="/",mustWork=TRUE)
workspace <- Sys.getenv("SYNDNET_READER_STUDY_ROOT","")
if(!nzchar(workspace)) stop("Set SYNDNET_READER_STUDY_ROOT to an approved controlled-data workspace outside the repository. See DATA_ACCESS.md.")
root <- normalizePath(workspace,winslash="/",mustWork=TRUE)
repo <- dirname(dirname(code_root))
if(root==repo || startsWith(root,paste0(repo,"/"))) stop("Controlled inputs and generated reader outputs must be outside the public repository.")
required <- c("input/MRMC_REAL_READER_CASE_FINAL.csv","input/MRMC_LOCKED_CASE_PREDICTIONS.csv","input/reader_assignment.csv","qc/expected_auc_fingerprint.csv")
if(!all(file.exists(file.path(root,required)))) stop("Controlled input bundle is incomplete; see the reader-study input format documentation.")
for(name in c("results","qc","environment")) dir.create(file.path(root,name),showWarnings=FALSE)
Sys.setenv(SYNDNET_READER_STUDY_ROOT=root,SYNDNET_READER_STUDY_CODE_ROOT=code_root)
for(name in c("00_input_qc.R","01_primary_imrmc.R","02_operating_glmm.R","03_secondary_glmm.R","04_safety_glmm.R","reader_intervals.R","05_publication_outputs.R","06_reproducibility_checks.R")) source(file.path(code_root,name),encoding="UTF-8")
writeLines(capture.output(sessionInfo()),file.path(root,"environment","sessionInfo_rerun.txt"))
